#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const JSDOM = require('./test-env.js').requireJsdom();
const { validateTripData } = require('./validate-trip-data.js');
const { readingSelection } = require('./supplementary-reading.js');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'guide-reading-'));
let revision = 0;
const renderHtml = data => {
  const input = path.join(temp, `reading-${++revision}.json`);
  const output = path.join(temp, `reading-${revision}.html`);
  fs.writeFileSync(input, JSON.stringify(data));
  const rendered = spawnSync(process.execPath, [path.join(__dirname, 'render-guide.js'), input, output, '--no-collaboration'], { encoding: 'utf8' });
  assert.equal(rendered.status, 0, rendered.stdout + rendered.stderr);
  return fs.readFileSync(output, 'utf8');
};
try {
  const file = path.join(temp, 'trip.json');
  const fixture = spawnSync(process.execPath, [path.join(__dirname, 'test-data-pipeline.js'), `--write-content-fixture=${file}`], { encoding: 'utf8' });
  assert.equal(fixture.status, 0, fixture.stderr);
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  data.sources.forEach(source => { delete source.reading; source.title = `PRIVATE-RESEARCH-${source.id}`; });
  data.sources[2].reading = { topic: '街区玩法', title: '老街完整步行路线', value: '包含支巷、院落及沿途建筑的详细图解' };
  data.sources[8].reading = { topic: '实用教程', title: '入境表逐项图文示例', value: '包含逐字段截图和提交后的确认页' };
  data.days[0].items[0].sourceIds = [1, 3, 9];
  data.days[0].items[0].details = ['柜台位于一层东门，08:00–20:00，费用50元。'];
  data.recommendations[0].image = { src: 'images/avatar.jpg', alt: '地点实拍', sourceId: 1 };
  data.sources[0].author = '图片作者';
  const original = JSON.stringify(data);
  const validated = validateTripData(data, { stage: 'content' });
  assert.equal(validated.valid, true);
  assert.equal(validated.summary.sources, 10);
  assert.equal(validated.summary.supplementaryReading, 2);
  const invalidIndex = structuredClone(data); invalidIndex.sourceIndex = {};
  assert.equal(validateTripData(invalidIndex, { stage: 'content' }).valid, false);
  const duplicate = structuredClone(data);
  duplicate.sources.push({ ...duplicate.sources[2], id: 11, url: duplicate.sources[2].url + '?share=other' });
  assert.equal(readingSelection(duplicate).sources.length, 2, '同笔记分享参数不制造重复阅读');
  const html = renderHtml(data);
  const document = new JSDOM(html).window.document;
  const selected = [...document.querySelectorAll('#sources li')];
  assert.deepEqual(selected.map(li => li.id), ['source-1', 'source-2']);
  assert.deepEqual(selected.map(li => li.value), [1, 2]);
  assert.equal(selected[0].querySelector('a').href, data.sources[2].url);
  assert.equal(selected[1].querySelector('a').href, data.sources[8].url);
  assert.equal(document.querySelector('#sources h2').textContent, '补充阅读');
  assert.ok(!document.querySelector('#sources').hidden);
  const refs = [...document.querySelectorAll('.source-ref')];
  assert.ok(refs.length > 0);
  assert.ok(refs.every(ref => document.querySelector(ref.getAttribute('href'))));
  assert.ok(document.body.textContent.includes('柜台位于一层东门，08:00–20:00，费用50元。'));
  assert.ok(document.querySelector('a[href="https://www.12306.cn/index/"]'), '操作入口不删');
  assert.ok(document.querySelector('.sourced-recommendation-image figcaption a').textContent.includes('图片作者'));
  assert.ok(document.querySelector('.sourced-recommendation-image figcaption a').href.includes('test-note-1'));
  const index = JSON.parse(document.querySelector('#travel-source-index').textContent);
  assert.deepEqual(index.map(item => item.sourceId), [1, 2]);
  assert.equal(index[0].title, data.sources[2].reading.title);
  assert.ok(!document.querySelector('#sources').textContent.includes('PRIVATE-RESEARCH'));
  assert.ok(!document.querySelector('#travel-source-index').textContent.includes('PRIVATE-RESEARCH'));
  assert.equal(JSON.stringify(data), original, '公开投影不回写私有研究数据');
  // A source can be removed from reading without deleting its evidence or facts.
  delete data.sources[2].reading;
  const renewed = new JSDOM(renderHtml(data)).window.document;
  assert.deepEqual(JSON.parse(renewed.querySelector('#travel-source-index').textContent).map(item => item.sourceId), [1]);
  assert.equal(renewed.querySelector('#source-1 a').href, data.sources[8].url);
  assert.equal(renewed.querySelector('#source-2'), null);
  data.sources.forEach(source => delete source.reading);
  delete data.sourceIndex;
  const empty = new JSDOM(renderHtml(data)).window.document;
  assert.ok(empty.querySelector('#sources').hidden);
  assert.equal(empty.querySelector('.source-ref, #travel-source-index'), null);
  assert.ok(empty.querySelector('#guide-search-advanced').disabled);
  assert.equal(validateTripData(data, { stage: 'content' }).valid, true);
  data.sources[0].reading = { topic: 'POI核验', title: '坐标', value: '' };
  assert.equal(validateTripData(data, { stage: 'content' }).valid, false);
  delete data.sources[0].reading;
  data.sources.pop(); data.researchAudit.xiaohongshuReadCount = 9;
  assert.match(validateTripData(data, { stage: 'content' }).failures.join('\n'), /至少 10 篇/);
  assert.equal(readingSelection(data).sources.length, 0);
  console.log('PASS curated reading: private research quota, public projection, contiguous references/search, image credits, execution details and zero-reading state');
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
