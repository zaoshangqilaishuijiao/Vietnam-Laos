#!/usr/bin/env node
const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { assertContentContinuity, stableContentKeys, parseArgs } = require("./publish-checklist.js");

const temp = fs.mkdtempSync(path.join(os.tmpdir(), "travel-guide-continuity-"));
const baselinePath = path.join(temp, "old.json");
const inputPath = path.join(temp, "new.json");
fs.writeFileSync(baselinePath, '{"version":1}\n');
fs.writeFileSync(inputPath, '{"version":2}\n');
const hash = value => crypto.createHash("sha256").update(value).digest("hex");
const baselineContentSha256 = hash("oldcontent"), inputContentSha256 = hash("newcontent");
const body = '<body data-guide-id="sameguide1"><li data-item-id="day1-a"></li><article data-venue-id="venue-a"></article><input data-check="ticket"><li id="source-1"></li><article id="recommendation-food"></article><img src="images/route.png"><a href="https://example.com/official">官网</a></body>';
const oldHtml = `<meta name="guide-content-sha256" content="${baselineContentSha256}">${body}`;
const newHtml = `<meta name="guide-content-sha256" content="${inputContentSha256}">${body}`;
const proof = { contentContinuity: { status: "enforced", inputPath, inputSha256: hash(fs.readFileSync(inputPath)), inputContentSha256, baselinePath, baselineDataSha256: hash(fs.readFileSync(baselinePath)), baselineContentSha256, baselineHtmlSha256: hash(oldHtml), allowPaths: ["days[0].items[0]"] } };
assert.doesNotThrow(() => assertContentContinuity(proof, newHtml, oldHtml));
assert.deepEqual([...stableContentKeys(oldHtml)].sort(), ["check:ticket", "image:images/route.png", "item:day1-a", "link:https://example.com/official", "recommendation:recommendation-food", "source:source-1", "venue:venue-a"].sort());
assert.equal(stableContentKeys('<script>const sample = `<img src="not-real.png">`;</script><style>.x{content:"<img src=\\"fake.png\\">"}</style>').size, 0);
assert.deepEqual(parseArgs(["--allow-removed-ids=link:https://example.com/?a=1,2,item:day1-a"]).allowRemovedIds, ["link:https://example.com/?a=1,2", "item:day1-a"]);
assert.throws(() => assertContentContinuity({}, newHtml, oldHtml), /没有内容连续性证明/);
const legacyHtml = oldHtml.replace(' data-guide-id="sameguide1"', '').replace(/<meta[^>]+>/, '');
const legacyProof = { contentContinuity: { ...proof.contentContinuity, baselineHtmlSha256: hash(legacyHtml) } };
assert.throws(() => assertContentContinuity({}, newHtml, legacyHtml), /没有内容连续性证明/);
assert.doesNotThrow(() => assertContentContinuity(legacyProof, newHtml, legacyHtml));
assert.throws(() => assertContentContinuity(legacyProof, newHtml.replace('<li data-item-id="day1-a"></li>', ''), legacyHtml), /item:day1-a/);
assert.throws(() => assertContentContinuity(proof, newHtml.replace(' data-guide-id="sameguide1"', ''), oldHtml), /guideId/);
assert.throws(() => assertContentContinuity(proof, newHtml, oldHtml + " "), /不是该发布路径的上一版/);
assert.throws(() => assertContentContinuity(proof, newHtml.replace("sameguide1", "otherguide1"), oldHtml), /guideId/);
assert.throws(() => assertContentContinuity({ contentContinuity: { ...proof.contentContinuity, baselineContentSha256: hash("stale") } }, newHtml, oldHtml), /不是最近一次发布/);
const lost = newHtml.replace('<li data-item-id="day1-a"></li>', "").replace('<img src="images/route.png">', "");
assert.throws(() => assertContentContinuity(proof, lost, oldHtml), /item:day1-a.*image:images\/route.png/);
assert.doesNotThrow(() => assertContentContinuity(proof, lost, oldHtml, ["item:day1-a", "image:images/route.png"]));
assert.throws(() => assertContentContinuity(proof, lost, oldHtml, ["item:day1-a", "image:images/route.png", "item:bogus"]), /未实际消失/);
fs.writeFileSync(inputPath, '{"version":3}\n');
assert.throws(() => assertContentContinuity(proof, newHtml, oldHtml), /已移动或变更/);
console.log("PASS published-guide content continuity gate");
