const assert = require('node:assert/strict'), fs = require('fs'), path = require('path');
const { JSDOM } = require('jsdom');
const html = '<div data-weather-card><button data-weather-refresh></button><p data-weather-status></p><div data-weather-grid></div></div>' +
  ['A', 'B', 'Unknown'].map(city => `<article data-itinerary-date="2026-10-21" data-city="${city}"><span data-day-weather></span></article>`).join('');
const dom = new JSDOM(html, { runScripts: 'outside-only', url: 'http://127.0.0.1:8766/' });
dom.window.eval(fs.readFileSync(path.join(__dirname, '../assets/travel-guide-interactions.js'), 'utf8'));
const locations = [{ name: 'A', placeId: 'a' }, { name: 'B', placeId: 'b' }];
const api = dom.window.TravelGuideInteractions.initWeatherForecast({ enabled: true, locations });
const row = { date: '2026-10-21', weather: '晴', chance: 0, min: 20, max: 25 };
api.render({ A: [row], B: [{ ...row, weather: '雷暴', chance: 95, min: 5, max: 9 }] });
const badges = dom.window.document.querySelectorAll('[data-day-weather]');
assert.equal(badges[0].textContent, '晴 · 降雨 0% · 20–25°C');
assert.equal(badges[1].textContent, '雷暴 · 降雨 95% · 5–9°C');
assert.equal(badges[2].textContent, '天气待刷新');
const cache = JSON.parse(dom.window.sessionStorage.getItem(dom.window.sessionStorage.key(0)));
assert.equal(cache.a[row.date].weather, '晴');
assert.equal(cache.b[row.date].weather, '雷暴');
const { dayWeatherPlaceId } = require('./render-guide.js');
const trip = { weather: { locations }, places: [{ id: 'a', city: 'A', country: 'X' }, { id: 'b', city: 'B', country: 'X' }] };
assert.equal(dayWeatherPlaceId({ city: 'A', items: [] }, trip), 'a');
assert.equal(dayWeatherPlaceId({ city: 'A → B', accommodation: { endPlaceId: 'b' }, items: [] }, trip), 'b');
assert.equal(dayWeatherPlaceId({ city: 'Unknown', items: [] }, trip), '');
dom.window.document.querySelector('[data-city="A"]').dataset.weatherPlaceId = 'b';
api.render({ a: [row], b: [{ ...row, weather: '雷暴', chance: 95, min: 5, max: 9 }] });
assert.equal(badges[0].textContent, '雷暴 · 降雨 95% · 5–9°C');
api.render({ a: [row] });
assert.equal(badges[1].textContent, '天气待刷新', 'partial failure must not use another city');
dom.window.close();
console.log('PASS weather remains bound to place/date, including partial failure');
